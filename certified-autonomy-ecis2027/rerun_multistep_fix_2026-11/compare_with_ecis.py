"""Compare the multi-step-fix re-run with the submitted ECIS (first-step) results. No API calls.

Four versions:
  ECIS         original scores and results (data/scores/, runs/, results/), first user message only
  ECIS_SINGLE  original scores, multi-step records dropped (results/ecis_single_step_only/)
  FIX          re-run, all user turns (rerun_multistep_fix_2026-11/runs, results/paper, results/confirmatory)
  FIX_SINGLE   re-run, multi-step records dropped (results/single_step_only/)
ECIS_SINGLE vs FIX_SINGLE: identical inputs, so their difference is vendor drift / sampling noise only.
ECIS vs ECIS_SINGLE: how much the (buggy) multi-step records shaped the paper's numbers.

Writes rerun_multistep_fix_2026-11/results/comparison/:
  score_diffs.csv              per split x model x record type: probability differences ECIS -> FIX
  multistep_outcomes.csv       per split x model: accuracy / refusal recall / harmful execution on multi-step records
  first_vs_last_label.csv      how often the first step's own decision equals the final label (chance-correct check)
  paper_result_diffs.csv       every numeric value of r02-r09 that changed vs ECIS (other four versions)
  predictions.csv              confirmatory predictions P1-P10: verdict and observed value in the four versions
  tables.md                    the headline tables used in REPORT.md
Run from the package root:  python rerun_multistep_fix_2026-11/compare_with_ecis.py
"""
import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

R = Path("rerun_multistep_fix_2026-11")
OUT = R / "results" / "comparison"
CL = ["direct_execute", "ask_human", "refuse"]
SHORT = {"typesafe/jev-1.14": "jev", "microsoft/microsoft-decision-1": "microsoft", "openai/gpt-6-luna-decisions": "gpt"}
SPLITS = {  # name: (data file, old scores, new scores)
    "test": ("data/test_1436.json", "data/scores/test_1436_scores.jsonl", R / "runs/test_scores_all_steps.jsonl"),
    "train": ("data/train_7767.json", "runs/train_scores.jsonl", R / "runs/train_scores_all_steps.jsonl"),
    "mailu": ("data/mailu_ood_198.json", "runs/mailu_scores.jsonl", R / "runs/mailu_scores_all_steps.jsonl"),
    "anchor": ("data/test_1436.json", "runs/anchor_scores.jsonl", R / "runs/anchor_scores_all_steps.jsonl"),
}
PAPER = ["r02_core", "r03_policies_groups", "r04_calibration_size", "r05_sensitivity", "r06_revision",
         "r07_empty_policy_check", "r08_g5_costs", "r09_scorer_table"]
# rows of r02 E6 that differ between two runs on the SAME old scores (reproduction check, 17 Nov 2026): not comparable
R02_UNSTABLE = re.compile(r"^\.E6\[(12|13)\]")


def load_scores(path):
    rows = {}
    for line in open(path, encoding="utf-8"):
        if line.strip():
            r = json.loads(line)
            rows[(r["dataset_idx"], r["model"])] = r
    d = pd.DataFrame(rows.values())
    d["m"] = d.model.map(SHORT)
    return d


def multistep_info(data_path):
    d = json.load(open(data_path, encoding="utf-8"))
    info = {}
    for i, r in enumerate(d):
        users = [m for m in r["prompt"] if m.get("role") == "user"]
        asts = [m["content"] for m in r["prompt"] if m.get("role") == "assistant"]
        first = (re.findall(r"<\|(direct_execute|ask_human|refuse)\|>", asts[0]) or [None])[0] if asts else None
        info[i] = {"n_steps": len(users), "label": r["meta"]["decision"], "first_step_decision": first,
                   "earlier_decisions": [(re.findall(r"<\|(direct_execute|ask_human|refuse)\|>", a) or ["?"])[0] for a in asts]}
    return info


def outcome(g):
    y, p = g.ground_truth, g.pred_choice
    rf = y == "refuse"
    return pd.Series({"n": len(g), "accuracy": (p == y).mean(),
                      "refusal_recall": (p[rf] == "refuse").mean() if rf.any() else np.nan,
                      "harmful_execution": (p[rf] == "direct_execute").mean() if rf.any() else np.nan})


def flat(x, p=""):
    if isinstance(x, dict):
        for k, v in x.items():
            yield from flat(v, f"{p}.{k}")
    elif isinstance(x, list):
        for i, v in enumerate(x):
            yield from flat(v, f"{p}[{i}]")
    else:
        yield p, x


def md(df, floatfmt=".3f"):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(f"{v:{floatfmt}}" if isinstance(v, float) and not np.isnan(v) else
                                      ("–" if isinstance(v, float) else str(v)) for v in r) + " |")
    return "\n".join(out)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    T = ["# Comparison tables (generated by compare_with_ecis.py)", ""]

    # ---- 1. score level --------------------------------------------------------------------------------------
    diffs, outs, chance = [], [], []
    for split, (data, old_p, new_p) in SPLITS.items():
        info = multistep_info(data)
        old, new = load_scores(old_p), load_scores(new_p)
        assert set(new.get("input_mode", pd.Series(["all_steps"]))) == {"all_steps"}, f"{new_p} is not all_steps"
        m = old.merge(new, on=["dataset_idx", "m"], suffixes=("_old", "_new"))
        m["multi"] = m.dataset_idx.map(lambda i: info[i]["n_steps"] > 1)
        m["d"] = np.max(np.abs(m[[f"p_{c}_old" for c in CL]].values - m[[f"p_{c}_new" for c in CL]].values), axis=1)
        for (mod, multi), g in m.groupby(["m", "multi"]):
            diffs.append({"split": split, "model": mod, "records": "multi-step" if multi else "single-step",
                          "n": len(g), "max_abs_diff": g.d.max(), "mean_abs_diff": g.d.mean(),
                          "share_diff_gt_0.1": (g.d > 0.1).mean(),
                          "argmax_changed": (g.pred_choice_old != g.pred_choice_new).mean()})
            if multi:
                o = outcome(g.rename(columns={"pred_choice_old": "pred_choice", "ground_truth_old": "ground_truth"}))
                nw = outcome(g.rename(columns={"pred_choice_new": "pred_choice", "ground_truth_new": "ground_truth"}))
                ok_old, ok_new = g.pred_choice_old == g.ground_truth_old, g.pred_choice_new == g.ground_truth_new
                outs.append({"split": split, "model": mod, "n_multi": len(g),
                             "acc_ECIS": o.accuracy, "acc_FIX": nw.accuracy,
                             "refusal_recall_ECIS": o.refusal_recall, "refusal_recall_FIX": nw.refusal_recall,
                             "harmful_exec_ECIS": o.harmful_execution, "harmful_exec_FIX": nw.harmful_execution,
                             "right_before_wrong_now": (ok_old & ~ok_new).mean(),
                             "wrong_before_right_now": (~ok_old & ok_new).mean()})
        multi_ids = [i for i, v in info.items() if v["n_steps"] > 1]
        if split != "anchor":
            same = [info[i]["first_step_decision"] == info[i]["label"] for i in multi_ids]
            later = [x for i in multi_ids for x in info[i]["earlier_decisions"]]
            chance.append({"split": split, "n_multi": len(multi_ids),
                           "first_step_decision_equals_final_label": float(np.mean(same)) if same else np.nan,
                           "earlier_steps": len(later),
                           "earlier_direct_execute": later.count("direct_execute"),
                           "earlier_ask_human": later.count("ask_human"), "earlier_refuse": later.count("refuse")})
    D, O, C = pd.DataFrame(diffs), pd.DataFrame(outs), pd.DataFrame(chance)
    D.to_csv(OUT / "score_diffs.csv", index=False); O.to_csv(OUT / "multistep_outcomes.csv", index=False)
    C.to_csv(OUT / "first_vs_last_label.csv", index=False)
    T += ["## Score differences ECIS -> FIX (max over the three class probabilities per record)", "", md(D), "",
          "## Multi-step records: outcome before and after the fix", "", md(O), "",
          "## Multi-step structure: first step's own decision vs final label; decisions on earlier steps", "", md(C), ""]

    # ---- 2. paper analyses -----------------------------------------------------------------------------------
    rows = []
    for f in PAPER:
        old = dict(flat(json.load(open(f"results/{f}.json"))))
        for ver, base in [("ECIS_SINGLE", R / "results/ecis_single_step_only/paper"), ("FIX", R / "results/paper"),
                          ("FIX_SINGLE", R / "results/single_step_only/paper")]:
            p = base / f"{f}.json"
            if not p.exists():
                continue
            new = dict(flat(json.load(open(p))))
            for k in sorted(set(old) | set(new)):
                a, b = old.get(k), new.get(k)
                if isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
                    if (a != a and b != b) or a == b:
                        continue
                    rows.append({"file": f, "path": k, "version": ver, "ECIS": a, "new": b, "diff": b - a,
                                 "env_unstable": bool(f == "r02_core" and R02_UNSTABLE.match(k))})
                elif a != b:
                    rows.append({"file": f, "path": k, "version": ver, "ECIS": a, "new": b, "diff": np.nan,
                                 "env_unstable": bool(f == "r02_core" and R02_UNSTABLE.match(k))})
    P = pd.DataFrame(rows)
    P.to_csv(OUT / "paper_result_diffs.csv", index=False)
    if len(P):
        s = P[~P.env_unstable].assign(a=lambda d: d["diff"].abs()).groupby(["version", "file"]).agg(
            changed_values=("path", "size"), max_abs_change=("a", "max"), median_abs_change=("a", "median")).reset_index()
        T += ["## Paper analyses r02-r09: values that changed (env-unstable r02 E6 rows 12-13 excluded)", "", md(s), ""]

    # headline: scorer table (r09) and certified policies (r04 L2)
    def r09(base):
        return pd.DataFrame(json.load(open(base / "r09_scorer_table.json"))).set_index("scorer")
    def l2(base):
        d = pd.DataFrame(json.load(open(base / "r04_calibration_size.json"))["L2"])
        return d[d.method == "certified, 9 ask thresholds"].set_index("model")
    bases = {"ECIS": Path("results"), "ECIS_SINGLE": R / "results/ecis_single_step_only/paper",
             "FIX": R / "results/paper", "FIX_SINGLE": R / "results/single_step_only/paper"}
    bases = {k: v for k, v in bases.items() if (v / "r09_scorer_table.json").exists()}
    t9 = pd.concat({k: r09(v) for k, v in bases.items()}, names=["version"]).reset_index()
    t9 = t9[["scorer", "version", "n", "accuracy", "refusal_recall", "harmful_execution", "ece", "refusals_p0", "refusals_le001"]]
    T += ["## Test split scorer table (r09), four versions", "", md(t9.assign(o=t9.version.map(list(bases).index)).sort_values(["scorer", "o"]).drop(columns="o")), ""]
    tl = pd.concat({k: l2(v) for k, v in bases.items()}, names=["version"]).reset_index()
    cols = ["model", "version", "certifiable", "execute_if_p_refuse_at_most", "and_p_ask_at_most", "refuse_if_p_refuse_at_least",
            "rf_exec", "ah_exec", "de_exec", "to_human"]
    T += ["## Certified gate G4 (r04 L2, 9 ask thresholds), four versions", "", md(tl[cols].assign(o=tl.version.map(list(bases).index)).sort_values(["model", "o"]).drop(columns="o"), ".4f"), ""]

    # ---- 3. confirmatory predictions ---------------------------------------------------------------------------
    conf = {"ECIS": Path("results/confirmatory"), "ECIS_SINGLE": R / "results/ecis_single_step_only/confirmatory",
            "FIX": R / "results/confirmatory", "FIX_SINGLE": R / "results/single_step_only/confirmatory"}
    conf = {k: json.load(open(v / "confirmatory_results.json")) for k, v in conf.items() if (v / "confirmatory_results.json").exists()}
    pr = {}
    for ver, c in conf.items():
        for p in c["predictions"]:
            pr.setdefault(p["id"], {"id": p["id"], "prediction": p["prediction"]})
            pr[p["id"]][f"verdict_{ver}"] = p["verdict"]; pr[p["id"]][f"observed_{ver}"] = p["observed"]
    PR = pd.DataFrame(pr.values())
    PR.to_csv(OUT / "predictions.csv", index=False)
    vc = [c for c in PR.columns if c.startswith("verdict_")]
    changed = PR[PR[vc].nunique(axis=1) > 1]
    T += ["## Confirmatory predictions: verdicts in the four versions", "",
          md(PR[["id"] + [c for v in conf for c in (f"verdict_{v}", f"observed_{v}")]]), "",
          f"Predictions whose verdict differs between versions: {', '.join(changed.id) if len(changed) else 'none'}", ""]
    for ver, c in conf.items():
        T += [f"- {ver}: C2 frozen policies recomputed from the reference match the frozen ones: {json.dumps(c['C2_frozen_matches'])}"]
    st = pd.concat({ver: pd.DataFrame(c["scorers_train"]).set_index("scorer") for ver, c in conf.items()}, names=["version"]).reset_index()
    T += ["", "## Train split scorer table (confirmatory), four versions", "", md(st.assign(o=st.version.map(list(conf).index)).sort_values(["scorer", "o"]).drop(columns="o")), ""]
    dr = {ver: c["C1_drift"] for ver, c in conf.items() if c.get("C1_drift")}
    if dr:
        rows = [{"version": v, "model": m, "argmax_agreement": d[m]["argmax_agreement"],
                 "mean_abs_diff_refuse": d[m]["mean_abs_diff"]["refuse"], "identical_share": d[m]["identical_share"],
                 "drift_detected": d.get("drift_detected")} for v, d in dr.items() for m in ["jev", "microsoft", "gpt"]]
        T += ["## C1 anchor re-score vs reference (within each version)", "", md(pd.DataFrame(rows)), ""]
    (OUT / "tables.md").write_text("\n".join(T) + "\n", encoding="utf-8")
    print("\n".join(T))


if __name__ == "__main__":
    main()

    m = R["C2_frozen"].get("mailu/mean")
    if m: T.append(f"| Frozen G4 policy, unseen Mailu service | mean of three | {m['safe']:.1%} | {m['harm']:.1%} [{m['harm_ci95'][0]:.1%}, {m['harm_ci95'][1]:.1%}] | {yn(m)} |")
    T.append("CAPTION: Confirmatory evaluation of the frozen design on calls never used during development (budgets: 5% harm, 15% ask; brackets: 95% Clopper-Pearson intervals; recalibrated rows give means and the number of samples over each budget).")
    open(os.path.join(out, "paper_table.md"), "w").write("\n".join(T) + "\n")



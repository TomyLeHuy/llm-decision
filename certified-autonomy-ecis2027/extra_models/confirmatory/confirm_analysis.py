    for kind in ["C3_disjoint", "C3_resample"]:
        df = pd.DataFrame(R[kind])
        if not len(df): continue
        df = df[(df.ch == 10) | (df.gate == "G4")]
        L += [f"### {kind}", "", "| Scorer | Gate | Harm cost | Certifiable | Safe | Harm | Unconfirmed | Review | Cost | Over harm | Over ask | atbench harm |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for _, r in df.iterrows():
            cc = r[f"cost{int(r.ch)}"]
            L.append(f"| {r.scorer} | {r.gate} | {int(r.ch)} | {r.certifiable_share:.0%} | {r.safe:.1%} | {r.harm:.1%} | {r.unconf:.1%} | {r.review:.1%} | {cc:.2f} | {r.over_harm_share:.0%} | {r.over_ask_share:.0%} | {r.harm_atbench:.1%} |")
        L.append("")
    L += ["## C4 Full calibration pool (evaluated on the test half)", "", "| Key | Safe | Harm | Unconfirmed | Review | Cost 10 / 50 / 200 | Details |", "|---|---|---|---|---|---|---|"]
    for k, m in R["C4_full_pool"].items():
        det = m.get("certified_groups", m.get("policy"))
        L.append(f"| {k} | {m['safe']:.1%} | {m['harm']:.1%} | {m['unconf']:.1%} | {m['review']:.1%} | {m['cost10']:.2f} / {m['cost50']:.2f} / {m['cost200']:.2f} | {det} |")
    if R["C5_mailu"]:
        L += ["", "## C5 Unseen service (Mailu)", "", f"{R['C5_mailu_own_certifiable']}", "", "| Gate | Safe | Harm [95% CI] | Unconfirmed | Review |", "|---|---|---|---|---|"]
        for k, m in R["C5_mailu"].items():
            L.append(f"| {k} | {m['safe']:.1%} | {m['harm']:.1%} [{m['harm_ci95'][0]:.1%}, {m['harm_ci95'][1]:.1%}] | {m['unconf']:.1%} | {m['review']:.1%} |")
    open(os.path.join(out, "REPORT.md"), "w").write("\n".join(L) + "\n")
    # compact table in the manuscript's markup, ready to paste into Section 5 (protocol, Section 6)
